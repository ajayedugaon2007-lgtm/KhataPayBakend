CREATE DATABASE IF NOT EXISTS khatapay_db
	CHARACTER SET utf8mb4
	COLLATE utf8mb4_unicode_ci;
USE khatapay_db;

CREATE TABLE IF NOT EXISTS users (
	id VARCHAR(100) PRIMARY KEY,
	name VARCHAR(100) NOT NULL,
	email VARCHAR(150) UNIQUE NOT NULL,
	phone VARCHAR(20) UNIQUE NOT NULL,
	password VARCHAR(255) NOT NULL,
	role VARCHAR(20) NOT NULL DEFAULT 'owner',
	business_name VARCHAR(150),
	address TEXT,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS businesses (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	name VARCHAR(150) NOT NULL,
	type VARCHAR(100) DEFAULT 'General Retail',
	gst VARCHAR(50) DEFAULT 'Not Provided',
	address TEXT,
	is_active TINYINT(1) DEFAULT 1,
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customers (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	name VARCHAR(100) NOT NULL,
	phone VARCHAR(20),
	balance DECIMAL(10,2) DEFAULT 0.00,
	is_get TINYINT(1) DEFAULT 1,
	last_date VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS transactions (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	customer_name VARCHAR(100) NOT NULL,
	amount DECIMAL(10,2) NOT NULL,
	is_gave TINYINT(1) NOT NULL,
	note TEXT,
	date_str VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payments (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	title VARCHAR(150) NOT NULL,
	mode VARCHAR(50) DEFAULT 'UPI',
	amount DECIMAL(10,2) NOT NULL,
	status VARCHAR(20) DEFAULT 'SUCCESS',
	time_str VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoices (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	inv_no VARCHAR(50) NOT NULL,
	customer_name VARCHAR(100) NOT NULL,
	amount DECIMAL(10,2) NOT NULL,
	status VARCHAR(20) DEFAULT 'Unpaid',
	date_str VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	name VARCHAR(150) NOT NULL,
	price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
	stock INT DEFAULT 0,
	unit VARCHAR(20) DEFAULT 'pcs',
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS expenses (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	category VARCHAR(100) NOT NULL,
	amount DECIMAL(10,2) NOT NULL,
	note TEXT,
	date_str VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS staff (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	name VARCHAR(100) NOT NULL,
	role VARCHAR(100) DEFAULT 'Staff',
	phone VARCHAR(20),
	salary DECIMAL(10,2) DEFAULT 0.00,
	attendance VARCHAR(20) DEFAULT 'Present',
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notifications (
	id INT AUTO_INCREMENT PRIMARY KEY,
	user_id VARCHAR(100) NOT NULL,
	title VARCHAR(150) NOT NULL,
	body TEXT NOT NULL,
	time_str VARCHAR(50),
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
